#!/usr/bin/env bash
set -euo pipefail

SYNC_TOOL=""
if [[ -x "csharp/sync" ]]; then
    SYNC_TOOL="$(pwd)/csharp/sync"
else
    FOUND=$(find . -name "sync" -perm +111 2>/dev/null | head -n 1)
    if [[ -n "$FOUND" ]]; then
        SYNC_TOOL="$(cd "$(dirname "$FOUND")" && pwd)/$(basename "$FOUND")"
    fi
fi

if [[ -z "$SYNC_TOOL" || ! -x "$SYNC_TOOL" ]]; then
    echo "Error: Could not locate executable sync tool in runfiles."
    find . -maxdepth 3
    exit 1
fi

DOTNET_PACK=$(find .. -maxdepth 2 -name "*csharp_pack*" -type d 2>/dev/null | head -n 1)
if [[ -n "$DOTNET_PACK" ]]; then
    export DOTNET_ROOT="$(cd "$DOTNET_PACK" && pwd)"
fi

echo "Using sync tool: $SYNC_TOOL"

# Setup temporary test workspace
TEST_WS=$(mktemp -d /tmp/rules_csharp_sync_test.XXXXXX)
trap 'rm -rf "$TEST_WS"' EXIT

mkdir -p "$TEST_WS/src/SampleLib"
cat << 'EOF' > "$TEST_WS/src/SampleLib/Greeter.cs"
namespace SampleLib;
public class Greeter
{
    public static string Greet() => "Hello, World!";
}
EOF

cat << 'EOF' > "$TEST_WS/src/SampleLib/BUILD.bazel"
load("@rules_csharp//csharp:defs.bzl", "csharp_library")

csharp_library(
    name = "sample_lib",
    srcs = ["Greeter.cs"],
)
EOF

# 1. Run sync tool on the test workspace
"$SYNC_TOOL" --workspace="$TEST_WS"

CSPROJ="$TEST_WS/src/SampleLib/sample_lib.bazel.csproj"
if [[ ! -f "$CSPROJ" ]]; then
    echo "FAILED: Expected $CSPROJ to be generated by CsprojSync."
    exit 1
fi

echo "Generated csproj content:"
cat "$CSPROJ"

# 2. Verify architectural contracts in PLAN.md Section 7
if ! grep -q "<EnableDefaultItems>false</EnableDefaultItems>" "$CSPROJ"; then
    echo "FAILED: <EnableDefaultItems>false</EnableDefaultItems> missing from generated csproj."
    exit 1
fi

if ! grep -q '<Compile Include="Greeter.cs" />' "$CSPROJ"; then
    echo "FAILED: <Compile Include=\"Greeter.cs\" /> missing from generated csproj."
    exit 1
fi

if ! grep -q "<Reference Include=\"sample_lib\">" "$CSPROJ"; then
    echo "FAILED: Reference to target missing from generated csproj."
    exit 1
fi

if ! grep -q "\.ref\.dll</HintPath>" "$CSPROJ"; then
    echo "FAILED: Reference HintPath does not point to .ref.dll."
    exit 1
fi

# 3. Verify round-trip idempotency using --check
"$SYNC_TOOL" --workspace="$TEST_WS" --check
echo "Idempotency check passed."

# 4. Modify workspace: add an additional .cs file without updating csproj
cat << 'EOF' > "$TEST_WS/src/SampleLib/Helper.cs"
namespace SampleLib;
public class Helper { public static int MagicNumber => 42; }
EOF

# --check must detect that the project is out of sync and exit non-zero
if "$SYNC_TOOL" --workspace="$TEST_WS" --check 2>/dev/null; then
    echo "FAILED: --check should have failed when new .cs file was added without syncing."
    exit 1
fi
echo "--check correctly detected out-of-sync workspace."

# Re-run sync tool to synchronize
"$SYNC_TOOL" --workspace="$TEST_WS"

# Verify Helper.cs is now included
if ! grep -q '<Compile Include="Helper.cs" />' "$CSPROJ"; then
    echo "FAILED: Helper.cs not included in updated csproj."
    exit 1
fi

# Verify --check passes now
"$SYNC_TOOL" --workspace="$TEST_WS" --check
echo "Round-trip synchronization verified successfully."
exit 0
